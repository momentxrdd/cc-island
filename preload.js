const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('ccApi', {
  onState: (cb) => ipcRenderer.on('state', (_e, d) => cb(d)),
  onSettings: (cb) => ipcRenderer.on('settings', (_e, s) => cb(s)),
  onMedia: (cb) => ipcRenderer.on('media', (_e, m) => cb(m)),
  media: (cmd) => ipcRenderer.send('media-cmd', cmd),
  onDemo: (cb) => ipcRenderer.on('demo', () => cb()),
  mouseOver: (over) => ipcRenderer.send('mouse-over', over),
  surface: (view) => ipcRenderer.send('surface', view),
  decide: (id, behavior, answers) => ipcRenderer.send('decide', id, behavior, answers),
  onPermNav: (cb) => ipcRenderer.on('perm-nav', (_e, d) => cb(d)),
  dismiss: (id) => ipcRenderer.send('dismiss', id),
  copy: (text) => ipcRenderer.send('copy', text),
  getDetail: (sid, n) => ipcRenderer.invoke('get-detail', sid, n),
  getTranscript: (sid) => ipcRenderer.invoke('get-transcript', sid),
  getUsage: () => ipcRenderer.invoke('get-usage'),
  onUsage: (cb) => ipcRenderer.on('usage', (_e, u) => cb(u)),
  getWeather: () => ipcRenderer.invoke('get-weather'),
  onWeather: (cb) => ipcRenderer.on('weather', (_e, w) => cb(w)),
  onPalette: (cb) => ipcRenderer.on('palette', () => cb()),
  onCtxWarn: (cb) => ipcRenderer.on('ctx-warn', (_e, d) => cb(d)),
  onTimer: (cb) => ipcRenderer.on('timer', (_e, t) => cb(t)),
  onTimerDone: (cb) => ipcRenderer.on('timer-done', (_e, d) => cb(d)),
  timer: (cmd, arg) => ipcRenderer.send('timer-cmd', cmd, arg),
  onCalendar: (cb) => ipcRenderer.on('calendar', (_e, c) => cb(c)),
  onCalAlert: (cb) => ipcRenderer.on('cal-alert', (_e, a) => cb(a)),
  calendar: (cmd) => ipcRenderer.send('cal-cmd', cmd),
  calendarRange: (from, days) => ipcRenderer.invoke('cal-range', from, days),
  openLink: (url) => ipcRenderer.send('open-link', url),
  openExternal: (url) => ipcRenderer.send('open-external', url),
  reply: (sid, text) => ipcRenderer.invoke('session-reply', sid, text),
  getHistory: () => ipcRenderer.invoke('get-history'),
  setRules: (list) => ipcRenderer.send('rules-set', list),
  history: (cmd, id) => ipcRenderer.send('history-cmd', cmd, id),
  onHistory: (cb) => ipcRenderer.on('history-changed', () => cb()),
  onGame: (cb) => ipcRenderer.on('game', (_e, v) => cb(v)),
  onOsd: (cb) => ipcRenderer.on('osd', (_e, o) => cb(o)),
  onNotice: (cb) => ipcRenderer.on('notice', (_e, n) => cb(n)),
  hold: (ms) => ipcRenderer.send('hold', ms),
  setSetting: (k, v) => ipcRenderer.send('set-setting', k, v),
  setLogin: (on) => ipcRenderer.send('set-login', on),
  hooks: (cmd, agent) => ipcRenderer.send('hooks-cmd', cmd, agent),
  app: (cmd) => ipcRenderer.send('app-cmd', cmd),
  onOpenSettings: (cb) => ipcRenderer.on('open-settings', () => cb()),
  onOpenFull: (cb) => ipcRenderer.on('open-full', () => cb()),
  onToggleFull: (cb) => ipcRenderer.on('toggle-full', () => cb()),
  getThemeInfo: () => ipcRenderer.invoke('get-theme-info'),
  onThemeChanged: (cb) => ipcRenderer.on('theme-changed', (_e, t) => cb(t)),
});
